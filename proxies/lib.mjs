export function mergeCandidates(lists) {
  const seen = new Map();
  for (const list of lists) {
    for (const c of list) if (c && !seen.has(c.server)) seen.set(c.server, c);
  }
  return [...seen.values()];
}

// Runs `check` over the candidates with bounded concurrency and returns the fastest working ones.
// `check` resolves to { country, latencyMs } or null. Brazilian exits are dropped here too, since
// the country a provider declares can be wrong.
export async function selectProxies(candidates, check, { concurrency = 50, keep = 10 } = {}) {
  const alive = [];
  let next = 0;
  const worker = async () => {
    while (next < candidates.length) {
      const c = candidates[next++];
      const r = await check(c.server).catch(() => null);
      if (r && r.country && r.country !== "BR") alive.push({ server: c.server, ...r });
    }
  };
  await Promise.all(Array.from({ length: concurrency }, worker));
  return alive.sort((a, b) => a.latencyMs - b.latencyMs).slice(0, keep);
}

export function buildPac(proxies) {
  if (!proxies.length) throw new Error("cannot build a PAC without proxies");
  for (const p of proxies) {
    const [ip, port, extra] = p.server.split(":");
    if (extra !== undefined || !isPublicIpv4(ip) || !/^\d{1,5}$/.test(port ?? "")) {
      throw new Error(`invalid proxy: ${p.server}`);
    }
  }
  // No DIRECT fallback: logging in from the real IP would silently bring the restriction back.
  const chain = proxies.map(p => `PROXY ${p.server}`).join("; ");
  return `// Generated by proxies/update.mjs. Only the Discord login goes through these proxies.
var PROXIED = ${JSON.stringify(PROXIED_HOSTS)};
var DIRECT = ${JSON.stringify(DIRECT_HOSTS)};

function matches(host, list) {
  for (var i = 0; i < list.length; i++) {
    if (host === list[i] || dnsDomainIs(host, "." + list[i])) return true;
  }
  return false;
}

function FindProxyForURL(url, host) {
  host = host.toLowerCase();
  if (matches(host, DIRECT) || !matches(host, PROXIED)) return "DIRECT";
  return ${JSON.stringify(chain)};
}
`;
}

export function buildList(proxies, now = new Date()) {
  return JSON.stringify({ generatedAt: now.toISOString(), proxies }, null, 2) + "\n";
}

export function parseTraceCountry(body) {
  return /^loc=([A-Z0-9]{2})$/m.exec(body)?.[1] ?? null;
}
